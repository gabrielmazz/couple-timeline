import type { QuizCategory, QuizQuestion } from './coupleQuiz'

type OptionSet = [string, string, string, string]

function makeQuestion(category: QuizCategory, index: number, prompt: string, options: OptionSet): QuizQuestion {
	return {
		id: `expansion-${category}-${index + 1}`,
		category,
		prompt,
		options: [
			{ id: 'a', label: options[0] },
			{ id: 'b', label: options[1] },
			{ id: 'c', label: options[2] },
			{ id: 'd', label: options[3] },
		],
		source: 'deck',
	}
}

function buildQuestions(category: QuizCategory, prompts: readonly string[], optionSets: readonly OptionSet[]): QuizQuestion[] {
	return prompts.map((prompt, index) => makeQuestion(category, index, prompt, optionSets[index % optionSets.length]))
}

